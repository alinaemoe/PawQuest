// Turns migrations/NNNN_name.sql into src/migrations.generated.ts. Metro cannot import .sql files,
// so the app consumes the generated module; a test checks that it matches the files on disk.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'migrations');
const pattern = /^(\d{4})_([a-z0-9_]+)\.sql$/;

const entries = readdirSync(dir)
  .sort()
  .map((file) => {
    const match = pattern.exec(file);
    if (match === null) {
      throw new Error(`Migration file name must look like 0001_name.sql: ${file}`);
    }
    return {
      version: Number(match[1]),
      name: match[2],
      sql: readFileSync(join(dir, file), 'utf8'),
    };
  });

const body = entries
  .map(
    (e) =>
      `  { version: ${e.version}, name: ${JSON.stringify(e.name)}, sql: ${JSON.stringify(e.sql)} },`,
  )
  .join('\n');

writeFileSync(
  join(root, 'src', 'migrations.generated.ts'),
  `// GENERATED by scripts/gen-migrations.mjs from migrations/*.sql. Do not edit by hand.\nimport type { Migration } from './migrate';\n\nexport const MIGRATIONS: readonly Migration[] = [\n${body}\n];\n`,
);
console.log(`generated ${String(entries.length)} migrations`);
